/**
 * Returns today's spark prompt based on the day of the year (0-364).
 */
export function getDailySpark(date: Date = new Date()): DailySpark {
  const now = new Date(date);
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = (now.getTime() - startOfYear.getTime()) + ((startOfYear.getTimezoneOffset() - now.getTimezoneOffset()) * 60 * 1000);
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  const index = Math.abs(dayOfYear % 365);
  return DAILY_SPARKS[index] || DAILY_SPARKS[0];
}
